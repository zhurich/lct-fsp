"""Что из профиля кандидата видит работодатель до того, как кандидат раскрыл контакты.

Правила применяются во всех местах, где сведения о кандидате отдаются работодателю: карточка в банке и
подборке, отклик на вакансию, ответ на регулярное задание.
"""

import re

from app.modules.candidates.models import CandidateProfile

CONTACT_PLACEHOLDER = "[контакт скрыт]"

# Контакты в свободном тексте: почта, ссылки и ники мессенджеров, телефон, произвольная ссылка.
_CONTACTS = re.compile(
    r"[\w.+-]+@[\w-]+(?:\.[\w-]+)+"
    r"|(?:https?://|www\.)\S+"
    r"|(?:t\.me|telegram\.me|vk\.com|wa\.me|github\.com|linkedin\.com)/\S+"
    r"|(?<![\w@])@[A-Za-z]\w{3,31}"
    # Ник после названия мессенджера считается контактом только через двоеточие или тире: «tg: name».
    # Без разделителя это обычный текст («Telegram Bot API»), а название внутри слова («Postgres») не в счёт.
    r"|(?<!\w)(?:telegram|телеграм\w*|тг|tg|whatsapp|ватсап\w*|вотсап\w*|skype|скайп\w*|discord|дискорд\w*)"
    r"\s*[:\-—]\s*@?[A-Za-z][\w.]{3,31}"
    r"|(?<![\d\w])(?:\+?\d[\s().-]{0,3}){10,14}\d(?!\d)",
    re.IGNORECASE,
)


def mask_contacts(text: str) -> str:
    """Заменяет контактные данные в свободном тексте заглушкой.

    Имя и контакты открываются работодателю только после согласия кандидата; текст «О себе» и ответы на
    задания показываются раньше, поэтому контакты из них вырезаются. Правила ловят типовые записи, а не
    любой способ передать контакт словами.
    """
    return _CONTACTS.sub(CONTACT_PLACEHOLDER, text)


def visible_experience(profile: CandidateProfile) -> float | None:
    """Стаж для работодателя; None — кандидат его скрыл."""
    return None if "experience" in profile.hidden_fields else profile.experience_years
